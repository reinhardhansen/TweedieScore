# Precision of the small-P slopes for log variance: Monte Carlo standard error
# of each RMSE relative to the RMSE, and the slope standard error it implies
# (delta method, var(log RMSE) = (mcse / rmse)^2, independent cells).
small_grid = [P for P in grid if P <= 0.0025]
relative_mcse(method) = [num(pick(A; model = "log_variance", P = P, approximation = method).rmse_mcse) /
                         num(pick(A; model = "log_variance", P = P, approximation = method).rmse) for P in small_grid]
dev = log.(small_grid) .- mean(log.(small_grid))
slope_mc_se(rel) = sqrt(sum((dev ./ sum(abs2, dev)) .^ 2 .* rel .^ 2))
for method in ("Explicit second order", "ISD*")
    rel = relative_mcse(method)
    note!("F.1: log variance, P <= 0.0025, $(method): Monte Carlo s.e. of each RMSE relative to the RMSE",
          pct(minimum(rel)) * " to " * pct(maximum(rel)))
    note!("F.1: log variance, $(method): slope s.e. implied by the Monte Carlo errors", f3(slope_mc_se(rel)))
end

