num(x) = x === missing ? NaN : Float64(x)
rms(v) = sqrt(mean(abs2, v))

"""The one row of `df` whose columns equal the given values (floats up to 1e-12)."""
function pick(df::DataFrame; kwargs...)
    keep = trues(nrow(df))
    for (col, value) in kwargs
        column = df[!, col]
        if value isa AbstractString
            keep .&= coalesce.(column .== value, false)
        else
            keep .&= coalesce.(abs.(num.(column) .- value) .<= 1e-12, false)
        end
    end
    count(keep) == 1 || error("expected one row for $(collect(kwargs)), found $(count(keep))")
    return df[findfirst(keep), :]
end

"""Value of a numeric field in a flat JSON file (no JSON package needed)."""
function json_number(path::AbstractString, key::AbstractString)
    text = read(path, String)
    m = match(Regex("\"" * key * "\"\\s*:\\s*([-+0-9.eE]+)"), text)
    m === nothing && error("no numeric field $key in $path")
    return parse(Float64, m.captures[1])
end

"""Number in the form \$m\\times10^{e}\$ with three decimals in the mantissa."""
function sci3(v::Real)
    m, e = split(@sprintf("%.3e", v), 'e')
    return "\$" * m * "\\times10^{" * string(parse(Int, e)) * "}\$"
end

"""Three decimals, or two significant decimals in scientific form below 0.001."""
function latex_number(v::Real)
    v == 0.0 && return "0.000"
    if abs(v) < 0.001
        m, e = split(@sprintf("%.2e", v), 'e')
        return "\$" * m * "\\times10^{" * string(parse(Int, e)) * "}\$"
    end
    return @sprintf("%.3f", v)
end

f2(v) = @sprintf("%.2f", v)
f3(v) = @sprintf("%.3f", v)
f4(v) = @sprintf("%.4f", v)
f6(v) = @sprintf("%.6f", v)
g(v) = @sprintf("%g", v)
pct(v) = @sprintf("%.1f%%", 100 * v)

function write_table(name, caption, label, colspec, header, body; notes = "")
    path = joinpath(OUT, name)
    open(path, "w") do io
        println(io, "% Generated by replication/make_tables.jl from ", IN)
        println(io, "\\providecommand{\\ISDp}{ISD\$^{\\ast}\$}")
        println(io, "\\begin{table}[!htbp]")
        println(io, "\\centering")
        println(io, "\\caption{", caption, "}")
        println(io, "\\label{", label, "}")
        println(io, "\\begin{tabular}{", colspec, "}")
        println(io, "\\toprule")
        foreach(l -> println(io, l), header)
        println(io, "\\midrule")
        foreach(l -> println(io, l), body)
        println(io, "\\bottomrule")
        println(io, "\\end{tabular}")
        isempty(notes) || println(io, "\\par\\smallskip\\footnotesize ", notes)
        println(io, "\\end{table}")
    end
    println("Wrote ", path)
end

